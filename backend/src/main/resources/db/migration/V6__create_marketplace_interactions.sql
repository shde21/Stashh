CREATE TABLE investor_watchlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investor_user_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    note VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT investor_watchlist_unique UNIQUE (investor_user_id, profile_id),
    CONSTRAINT investor_watchlist_investor_fk FOREIGN KEY (investor_user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT investor_watchlist_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE
);

CREATE INDEX investor_watchlist_investor_idx ON investor_watchlist (investor_user_id, updated_at DESC);

CREATE TABLE investor_interest_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    investor_user_id BIGINT NOT NULL,
    profile_id BIGINT NOT NULL,
    message VARCHAR(2000),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT investor_interest_unique UNIQUE (investor_user_id, profile_id),
    CONSTRAINT investor_interest_investor_fk FOREIGN KEY (investor_user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT investor_interest_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT investor_interest_status_check CHECK (status IN ('PENDING', 'WITHDRAWN'))
);

CREATE INDEX investor_interest_profile_idx ON investor_interest_requests (profile_id, status, updated_at DESC);
