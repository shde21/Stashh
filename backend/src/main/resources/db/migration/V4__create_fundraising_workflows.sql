CREATE TABLE fundraising_pools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    title VARCHAR(180) NOT NULL,
    target_amount DECIMAL(20, 2) NOT NULL,
    min_commitment DECIMAL(20, 2) NOT NULL,
    max_commitment DECIMAL(20, 2),
    valuation_cap DECIMAL(20, 2),
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    opens_at TIMESTAMP WITH TIME ZONE,
    ends_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fundraising_pools_profile_unique UNIQUE (profile_id),
    CONSTRAINT fundraising_pools_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT fundraising_pools_title_nonblank CHECK (length(trim(title)) > 1),
    CONSTRAINT fundraising_pools_target_positive CHECK (target_amount > 0),
    CONSTRAINT fundraising_pools_min_positive CHECK (min_commitment > 0),
    CONSTRAINT fundraising_pools_max_valid CHECK (max_commitment IS NULL OR max_commitment >= min_commitment),
    CONSTRAINT fundraising_pools_min_under_target CHECK (min_commitment <= target_amount),
    CONSTRAINT fundraising_pools_status_check CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED'))
);

CREATE INDEX fundraising_pools_status_idx ON fundraising_pools (status);

CREATE TABLE fundraising_commitments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id BIGINT NOT NULL,
    investor_user_id BIGINT NOT NULL,
    amount DECIMAL(20, 2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fundraising_commitments_unique UNIQUE (pool_id, investor_user_id),
    CONSTRAINT fundraising_commitments_pool_fk FOREIGN KEY (pool_id) REFERENCES fundraising_pools (id) ON DELETE CASCADE,
    CONSTRAINT fundraising_commitments_investor_fk FOREIGN KEY (investor_user_id) REFERENCES app_users (id),
    CONSTRAINT fundraising_commitments_amount_positive CHECK (amount > 0),
    CONSTRAINT fundraising_commitments_status_check CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

CREATE INDEX fundraising_commitments_investor_idx ON fundraising_commitments (investor_user_id, status);
