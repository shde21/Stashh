    profile_id, authorized_shares, issued_shares, outstanding_shares, treasury_shares, reserved_shares, share_class, par_value
)
SELECT id, 10000000, 1000000, 1000000, 0, 0, 'EQUITY', 10.00
  FROM startup_profiles sp
