-- Add share pricing and share volume columns to fundraising pools
ALTER TABLE fundraising_pools ADD COLUMN price_per_share DECIMAL(20, 4) DEFAULT 10.0000 NOT NULL;
ALTER TABLE fundraising_pools ADD COLUMN total_shares_offered BIGINT DEFAULT 100000 NOT NULL;
ALTER TABLE fundraising_pools ADD COLUMN shares_allocated BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE fundraising_pools ADD COLUMN round_valuation_basis DECIMAL(20, 2);

-- Backfill existing fundraising pools with explicit valuation basis and shares offered
UPDATE fundraising_pools
   SET round_valuation_basis = valuation_cap,
       price_per_share = CASE
           WHEN valuation_cap IS NOT NULL AND valuation_cap > 0 THEN (valuation_cap / 1000000.0)
           ELSE 10.0000
       END;

UPDATE fundraising_pools
   SET total_shares_offered = CASE
           WHEN price_per_share > 0 THEN CAST(FLOOR(target_amount / price_per_share) AS BIGINT)
           ELSE 100000
       END;

-- Add share allocation and locked issue price columns to fundraising commitments
ALTER TABLE fundraising_commitments ADD COLUMN shares_allocated BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE fundraising_commitments ADD COLUMN price_per_share DECIMAL(20, 4) DEFAULT 10.0000 NOT NULL;

-- Backfill existing commitments with legitimate company-specific shares
UPDATE fundraising_commitments
   SET price_per_share = COALESCE((SELECT p.price_per_share FROM fundraising_pools p WHERE p.id = fundraising_commitments.pool_id), 10.0000);

UPDATE fundraising_commitments
   SET shares_allocated = CASE
           WHEN price_per_share > 0 THEN CAST(FLOOR(amount / price_per_share) AS BIGINT)
           ELSE 0
       END;

-- Recalculate allocated shares for each pool from active commitments
UPDATE fundraising_pools
   SET shares_allocated = COALESCE((
       SELECT SUM(c.shares_allocated)
         FROM fundraising_commitments c
        WHERE c.pool_id = fundraising_pools.id AND c.status = 'ACTIVE'
   ), 0);
