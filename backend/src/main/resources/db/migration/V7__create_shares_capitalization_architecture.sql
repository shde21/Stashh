-- V7: Implement company-specific equity shares and capitalization architecture

CREATE TABLE company_capitalization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL UNIQUE,
    authorized_shares BIGINT NOT NULL,
    issued_shares BIGINT NOT NULL,
    outstanding_shares BIGINT NOT NULL,
    treasury_shares BIGINT NOT NULL DEFAULT 0,
    reserved_shares BIGINT NOT NULL DEFAULT 0,
    share_class VARCHAR(64) NOT NULL DEFAULT 'EQUITY',
    par_value DECIMAL(20, 2) NOT NULL DEFAULT 10.00,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT company_capitalization_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT company_capitalization_auth_check CHECK (authorized_shares >= issued_shares + reserved_shares),
    CONSTRAINT company_capitalization_issued_check CHECK (issued_shares = outstanding_shares + treasury_shares),
    CONSTRAINT company_capitalization_positive CHECK (authorized_shares > 0 AND outstanding_shares > 0)
);

CREATE INDEX company_capitalization_profile_idx ON company_capitalization (profile_id);

