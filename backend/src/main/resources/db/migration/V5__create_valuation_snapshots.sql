CREATE TABLE valuation_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    admin_user_id BIGINT NOT NULL,
    valuation_amount DECIMAL(20, 2) NOT NULL,
    snapshot_at TIMESTAMP WITH TIME ZONE NOT NULL,
    note VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT valuation_snapshots_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT valuation_snapshots_admin_fk FOREIGN KEY (admin_user_id) REFERENCES app_users (id),
    CONSTRAINT valuation_snapshots_amount_positive CHECK (valuation_amount > 0)
);

CREATE INDEX valuation_snapshots_profile_date_idx ON valuation_snapshots (profile_id, snapshot_at DESC, id DESC);
