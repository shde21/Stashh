CREATE TABLE startup_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    company_name VARCHAR(160) NOT NULL,
    tagline VARCHAR(240),
    description VARCHAR(4000),
    website VARCHAR(500),
    sector VARCHAR(100),
    headquarters VARCHAR(160),
    founded_year INTEGER,
    startup_stage VARCHAR(32) NOT NULL DEFAULT 'PRE_REVENUE',
    team_size INTEGER,
    pitch_url VARCHAR(500),
    review_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    visibility VARCHAR(32) NOT NULL DEFAULT 'PRIVATE',
    review_note VARCHAR(2000),
    submitted_at TIMESTAMP WITH TIME ZONE,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT startup_profiles_user_unique UNIQUE (user_id),
    CONSTRAINT startup_profiles_user_fk FOREIGN KEY (user_id) REFERENCES app_users (id),
    CONSTRAINT startup_profiles_stage_check CHECK (startup_stage IN ('PRE_REVENUE', 'EARLY_REVENUE', 'GROWTH')),
    CONSTRAINT startup_profiles_status_check CHECK (review_status IN ('DRAFT', 'SUBMITTED', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED')),
    CONSTRAINT startup_profiles_visibility_check CHECK (visibility IN ('PRIVATE', 'PUBLIC')),
    CONSTRAINT startup_profiles_name_nonblank CHECK (length(trim(company_name)) > 1)
);

CREATE INDEX startup_profiles_review_status_idx ON startup_profiles (review_status);
CREATE INDEX startup_profiles_visibility_idx ON startup_profiles (visibility);

CREATE TABLE startup_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    metric_key VARCHAR(64) NOT NULL,
    metric_value DECIMAL(20, 4) NOT NULL,
    CONSTRAINT startup_metrics_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT startup_metrics_unique UNIQUE (profile_id, metric_key)
);

CREATE TABLE startup_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    kind VARCHAR(32) NOT NULL,
    title VARCHAR(180) NOT NULL,
    resource_url VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT startup_documents_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT startup_documents_kind_check CHECK (kind IN ('PITCH_DECK', 'FINANCIALS', 'OTHER'))
);

CREATE TABLE startup_review_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    admin_user_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    note VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT startup_review_actions_profile_fk FOREIGN KEY (profile_id) REFERENCES startup_profiles (id) ON DELETE CASCADE,
    CONSTRAINT startup_review_actions_admin_fk FOREIGN KEY (admin_user_id) REFERENCES app_users (id),
    CONSTRAINT startup_review_actions_action_check CHECK (action IN ('SUBMITTED', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED', 'MADE_PRIVATE', 'MADE_PUBLIC'))
);

CREATE INDEX startup_review_actions_profile_idx ON startup_review_actions (profile_id, created_at);
